/**
 * Python mock of {@code studioquack_helper} written next to the script under test.
 *
 * <p>{@code execute} returns {@code mock_function_responses[port]},
 * {@code getInputValuesByPortValue} reads {@code input.json},
 * {@code getParameterValueByShortCode} reads {@code configuration.json}, and
 * {@code returnResult} writes a port→value object to {@code output.json}.
 */
public final class PythonMockHelperSource {

    private PythonMockHelperSource() {
        // Source holder — never instantiated.
    }

    /**
     * CPython 3 source. Reads {@code input.json}, {@code mock_responses.json} and
     * {@code configuration.json} from the process cwd (the temp test dir).
     */
    public static String source() {
        return """
# Auto-generated by Node Test Emulator — mock of studioquack_helper for script tests.
# Not the real helper.py; execute() never leaves this process.
import json
import os
import sys

# Typed business error for scripts. errorCode is required; blank / SQ_SKIP raise ValueError.
class StudioQuackError(Exception):
    def __init__(self, errorCode, message=None, data=None):
        code = _require_error_code(errorCode)
        self.errorCode = code
        self.message = message
        self.data = data
        super().__init__(message if message is not None else code)


def _require_error_code(errorCode):
    code = '' if errorCode is None else str(errorCode).strip()
    if not code:
        raise ValueError('errorCode must be non-blank')
    if code.upper() == 'SQ_SKIP':
        raise ValueError("errorCode 'SQ_SKIP' is reserved")
    return code


OUTPUT_PATH = os.path.join(os.getcwd(), 'output.json')
INVOCATION_LOG_PATH = os.path.join(os.getcwd(), 'invocation_log.json')


def _load_json(name, default):
    path = os.path.join(os.getcwd(), name)
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception:
        return default


class StudioQuackHelper:
    class ResultItem:
        def __init__(self, port_value, result):
            self.portValue = port_value
            self.result = result

    def __init__(self):
        self.test_input_data = _load_json('input.json', {})
        if not isinstance(self.test_input_data, dict):
            self.test_input_data = {}
        self.mock_responses = _load_json('mock_responses.json', {})
        if not isinstance(self.mock_responses, dict):
            self.mock_responses = {}
        self.configuration = _load_json('configuration.json', {})
        if not isinstance(self.configuration, dict):
            self.configuration = {}
        self.invocation_log = []
        self._cancelled = False
        self._cancel_callbacks = []
        # Minimal fake context so scripts that call getExecutionContext() do not crash.
        self.execution_context = {
            'workflowExecutionId': 'test-execution-id',
            'currentNode': {
                'id': 'test-node-id',
                'connectionList': [],
                'data': {
                    'configurationParameters': [
                        {'shortCode': k, 'value': v} for k, v in self.configuration.items()
                    ],
                    'ports': []
                },
                'inputList': [
                    {'targetPortValue': k, 'value': v} for k, v in self.test_input_data.items()
                ],
                'outputList': [],
                'edgeTransformListForCurrentNode': []
            }
        }

    def execute(self, port_value, node_request, node_id=None):
        # FUNCTION-port mock. variable/provider ports are ignored (they no longer exist here).
        entry = {
            'port_value': port_value,
            'payload': node_request,
            'node_id': node_id,
            'mocked': port_value in self.mock_responses
        }
        self.invocation_log.append(entry)
        self._flush_log()
        if port_value in self.mock_responses:
            return self.mock_responses[port_value]
        print(
            f"Emulator Warning: No mock response for function port '{port_value}'",
            file=sys.stderr
        )
        return {}

    def getExecutionContext(self):
        ctx = self.execution_context
        return ctx if isinstance(ctx, dict) else {}

    def getWorkflowExecutionId(self):
        return self.getExecutionContext().get('workflowExecutionId', '')

    def getCurrentNode(self):
        node = self.getExecutionContext().get('currentNode')
        return node if isinstance(node, dict) else {}

    def getCurrentNodeId(self):
        return self.getCurrentNode().get('id', '')

    def getInput(self):
        input_list = self.getCurrentNode().get('inputList', [])
        return input_list if isinstance(input_list, list) else []

    def getInputValuesByPortValue(self, port_value, node_id=None):
        val = self.test_input_data.get(port_value)
        if val is not None:
            return val if isinstance(val, list) else [val]
        result = [
            item.get('value') for item in self.getInput()
            if isinstance(item, dict) and item.get('targetPortValue') == port_value
            and (node_id is None or item.get('nodeId') == node_id)
        ]
        return result

    def getOutput(self):
        out = self.getCurrentNode().get('outputList', [])
        return out if isinstance(out, list) else []

    def returnResult(self, items):
        # Capture EVERY ResultItem keyed by port value (expected_output is port → value).
        captured = {}
        if items:
            for item in items:
                port = getattr(item, 'portValue', None)
                if port:
                    captured[port] = getattr(item, 'result', None)
        with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
            json.dump(captured, f, indent=2)
        self._flush_log()
        sys.exit(0)

    def getTemplate(self):
        data = self.getCurrentNode().get('data', {})
        return data if isinstance(data, dict) else {}

    def getParameters(self):
        params = self.getTemplate().get('configurationParameters', [])
        return params if isinstance(params, list) else []

    def getParameterByShortCode(self, short_code):
        for param in self.getParameters():
            if isinstance(param, dict) and param.get('shortCode') == short_code:
                return param
        return None

    def getParameterValueByShortCode(self, short_code, return_value=None):
        if isinstance(self.configuration, dict) and short_code in self.configuration:
            return self.configuration.get(short_code)
        # Legacy fallback: configuration nested inside input_data.
        nested = self.test_input_data.get('configuration', {})
        if isinstance(nested, dict) and short_code in nested:
            return nested.get(short_code)
        parameter = self.getParameterByShortCode(short_code)
        if parameter:
            return parameter.get('value', return_value)
        return return_value

    def getConnections(self):
        return self.getCurrentNode().get('connectionList', [])

    # Camunda-style mock: prints SQ_MOCK / SQ_FAIL markers and does not call the helper channel.

    def fail(self, errorCode, message=None, data=None):
        code = _require_error_code(errorCode)
        print(f'SQ_FAIL {code}: {message}', file=sys.stderr)
        print(f'SQ_MOCK fail errorCode={code}')
        self.invocation_log.append({
            'type': 'fail',
            'errorCode': code,
            'message': message,
            'data': data,
        })
        self._flush_log()
        sys.exit(1)

    def escalate(self, escalationCode, message=None, data=None):
        print(f'SQ_MOCK escalate escalationCode={escalationCode}')
        self.invocation_log.append({
            'type': 'escalate',
            'escalationCode': escalationCode,
            'message': message,
            'data': data,
        })
        self._flush_log()

    def sendSignal(self, signalName, scope='global'):
        name = '' if signalName is None else str(signalName)
        if name.startswith('__sq_'):
            raise ValueError('signalName must not start with __sq_')
        print(f'SQ_MOCK sendSignal signalName={signalName} scope={scope}')
        self.invocation_log.append({
            'type': 'sendSignal',
            'signalName': signalName,
            'scope': scope,
        })
        self._flush_log()

    def sendMessage(self, messageName, correlationKey=None):
        print(f'SQ_MOCK sendMessage messageName={messageName} correlationKey={correlationKey}')
        self.invocation_log.append({
            'type': 'sendMessage',
            'messageName': messageName,
            'correlationKey': correlationKey,
        })
        self._flush_log()

    def isCancelled(self):
        return self._cancelled

    def onCancel(self, callback):
        if self._cancelled:
            self._invoke_cancel_callback(callback)
            return
        self._cancel_callbacks.append(callback)

    def handleCancel(self, requestId, reason=None):
        self._cancelled = True
        pending = list(self._cancel_callbacks)
        self._cancel_callbacks.clear()
        for callback in pending:
            self._invoke_cancel_callback(callback)
        self.invocation_log.append({
            'type': 'handleCancel',
            'requestId': requestId,
            'reason': reason,
        })
        self._flush_log()

    def _invoke_cancel_callback(self, callback):
        try:
            if callable(callback):
                callback()
        except Exception:
            pass

    def _flush_log(self):
        try:
            with open(INVOCATION_LOG_PATH, 'w', encoding='utf-8') as f:
                json.dump(self.invocation_log, f, indent=2)
        except Exception:
            pass


studioquack = StudioQuackHelper()
""";
    }
}
