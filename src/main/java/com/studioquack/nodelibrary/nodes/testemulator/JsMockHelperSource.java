package com.studioquack.nodelibrary.nodes.testemulator;

/**
 * CommonJS mock of {@code studioquack_helper} for JavaScript and TypeScript tests.
 *
 * <p>Same API as {@link PythonMockHelperSource}: {@code getInputValuesByPortValue},
 * {@code getParameterValueByShortCode}, {@code execute}, {@code returnResult} (writes
 * {@code output.json} keyed by port), {@code ResultItem}, singleton {@code studioquack}.
 *
 * <p>TypeScript tests are run with {@code tsx}, which can {@code require()} this
 * {@code .js} file directly. Variable/provider ports are not implemented.
 */
public final class JsMockHelperSource {

    private JsMockHelperSource() {
        // Source holder — never instantiated.
    }

    /** Node.js CommonJS source. Reads JSON sidecars from {@code process.cwd()}. */
    public static String source() {
        return """
// Auto-generated by Node Test Emulator — CommonJS mock of studioquack_helper.
// TS scripts (tsx) can require() this file. execute() never leaves this process.
'use strict';
const fs = require('fs');
const path = require('path');

const OUTPUT_PATH = path.join(process.cwd(), 'output.json');
const INVOCATION_LOG_PATH = path.join(process.cwd(), 'invocation_log.json');

function loadJson(name, fallback) {
  try {
    const raw = fs.readFileSync(path.join(process.cwd(), name), 'utf8');
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? parsed : fallback;
  } catch (e) {
    return fallback;
  }
}

class ResultItem {
  constructor(portValue, result) {
    this.portValue = portValue;
    this.result = result;
  }
}

class StudioQuackHelper {
  constructor() {
    this.ResultItem = ResultItem;
    this.test_input_data = loadJson('input.json', {});
    this.mock_responses = loadJson('mock_responses.json', {});
    this.configuration = loadJson('configuration.json', {});
    this.invocation_log = [];
    const configParams = Object.keys(this.configuration).map((k) => ({
      shortCode: k,
      value: this.configuration[k]
    }));
    const inputList = Object.keys(this.test_input_data).map((k) => ({
      targetPortValue: k,
      value: this.test_input_data[k]
    }));
    this.execution_context = {
      workflowExecutionId: 'test-execution-id',
      currentNode: {
        id: 'test-node-id',
        connectionList: [],
        data: { configurationParameters: configParams, ports: [] },
        inputList: inputList,
        outputList: [],
        edgeTransformListForCurrentNode: []
      }
    };
  }

  execute(port_value, node_request, node_id) {
    const entry = {
      port_value: port_value,
      payload: node_request,
      node_id: node_id == null ? null : node_id,
      mocked: Object.prototype.hasOwnProperty.call(this.mock_responses, port_value)
    };
    this.invocation_log.push(entry);
    this._flushLog();
    if (Object.prototype.hasOwnProperty.call(this.mock_responses, port_value)) {
      return this.mock_responses[port_value];
    }
    process.stderr.write(
      "Emulator Warning: No mock response for function port '" + port_value + "'\\n"
    );
    return {};
  }

  getExecutionContext() {
    return this.execution_context && typeof this.execution_context === 'object'
      ? this.execution_context
      : {};
  }

  getWorkflowExecutionId() {
    return this.getExecutionContext().workflowExecutionId || '';
  }

  getCurrentNode() {
    const node = this.getExecutionContext().currentNode;
    return node && typeof node === 'object' ? node : {};
  }

  getCurrentNodeId() {
    return this.getCurrentNode().id || '';
  }

  getInput() {
    const list = this.getCurrentNode().inputList;
    return Array.isArray(list) ? list : [];
  }

  getInputValuesByPortValue(port_value, node_id) {
    const val = this.test_input_data[port_value];
    if (typeof val !== 'undefined') {
      return Array.isArray(val) ? val : [val];
    }
    return this.getInput()
      .filter((item) => item && item.targetPortValue === port_value
        && (node_id == null || item.nodeId === node_id))
      .map((item) => item.value);
  }

  getOutput() {
    const list = this.getCurrentNode().outputList;
    return Array.isArray(list) ? list : [];
  }

  returnResult(items) {
    const captured = {};
    if (Array.isArray(items)) {
      for (const item of items) {
        if (item && item.portValue) {
          captured[item.portValue] = item.result;
        }
      }
    }
    fs.writeFileSync(OUTPUT_PATH, JSON.stringify(captured, null, 2), 'utf8');
    this._flushLog();
    process.exit(0);
  }

  getTemplate() {
    const data = this.getCurrentNode().data;
    return data && typeof data === 'object' ? data : {};
  }

  getParameters() {
    const params = this.getTemplate().configurationParameters;
    return Array.isArray(params) ? params : [];
  }

  getParameterByShortCode(short_code) {
    return this.getParameters().find((p) => p && p.shortCode === short_code) || null;
  }

  getParameterValueByShortCode(short_code, return_value) {
    if (Object.prototype.hasOwnProperty.call(this.configuration, short_code)) {
      return this.configuration[short_code];
    }
    const nested = this.test_input_data.configuration;
    if (nested && typeof nested === 'object'
        && Object.prototype.hasOwnProperty.call(nested, short_code)) {
      return nested[short_code];
    }
    const parameter = this.getParameterByShortCode(short_code);
    if (parameter) {
      return typeof parameter.value === 'undefined' ? return_value : parameter.value;
    }
    return typeof return_value === 'undefined' ? null : return_value;
  }

  getConnections() {
    const list = this.getCurrentNode().connectionList;
    return Array.isArray(list) ? list : [];
  }

  _flushLog() {
    try {
      fs.writeFileSync(INVOCATION_LOG_PATH, JSON.stringify(this.invocation_log, null, 2), 'utf8');
    } catch (e) {
      /* ignore flush errors — the test still has stderr warnings */
    }
  }
}

const studioquack = new StudioQuackHelper();
module.exports = { studioquack, StudioQuackHelper, ResultItem };
""";
    }
}
